public class Test {
    public static void main(String[] args) {
        // Khai báo hai biến số nguyên
        int a = 15;
        int b = 5;

        // Biểu thức cộng
        int tong = a + b;
        System.out.println("Phép cộng: " + a + " + " + b + " = " + tong);

        // Biểu thức trừ
        int hieu = a - b;
        System.out.println("Phép trừ: " + a + " - " + b + " = " + hieu);
    }
}